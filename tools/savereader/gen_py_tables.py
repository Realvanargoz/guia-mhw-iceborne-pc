"""Generate the data used by the pure-Python save reader (api/app/savereader) from this C# project.

* ``api/app/savereader/_iceborne_tables.py``: INTEGER_CONSTANTS and FLOAT_CONSTANTS of
  Vendor/MHWCrypto/CryptoSecondLayer.cs. Floats are stored as their exact IEEE-754 binary32 bit patterns,
  obtained by correctly rounding each decimal literal to float32 (what Roslyn does for ``0.123F``), so the
  Python side never re-parses decimals.
* ``api/app/savereader/data/*.json``: byte-for-byte copies of the embedded resources listed in
  MhwSaveReader.csproj.

Usage: python tools/savereader/gen_py_tables.py   (idempotent; only writes inside api/app/savereader)
"""
from __future__ import annotations

import re
import shutil
import struct
import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "api" / "app" / "savereader"
CS = HERE / "Vendor" / "MHWCrypto" / "CryptoSecondLayer.cs"
RESOURCES = ["jewels.json", "equipment.json", "quest_order.json", "monsters128.json"]


def _block(src: str, name: str) -> str:
    m = re.search(name + r"\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit(f"{name} not found in {CS}")
    return m.group(1)


def f32_bits(literal: str) -> int:
    """Correctly rounded (nearest, ties-to-even) decimal -> binary32, returned as raw bits."""
    q = Fraction(literal)
    if q == 0:
        return 0
    neg = q < 0
    q = abs(q)
    e = q.numerator.bit_length() - q.denominator.bit_length()
    while Fraction(2) ** e > q:
        e -= 1
    while Fraction(2) ** (e + 1) <= q:
        e += 1
    e = max(e, -126)  # subnormal range shares the minimum exponent
    scaled = q / (Fraction(2) ** (e - 23))
    m = scaled.numerator // scaled.denominator
    rem = scaled - m
    if rem > Fraction(1, 2) or (rem == Fraction(1, 2) and m & 1):
        m += 1
    value = Fraction(m) * Fraction(2) ** (e - 23)
    bits = struct.unpack("<I", struct.pack("<f", float(value)))[0]  # exact: value has <= 24 significant bits
    return bits | (0x80000000 if neg else 0)


def main() -> int:
    src = CS.read_text(encoding="utf-8-sig")
    ints = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", _block(src, "INTEGER_CONSTANTS"))]
    flts = re.findall(r"(-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)[fF]", _block(src, "FLOAT_CONSTANTS"))
    if len(ints) != 4096 or len(flts) != 4096:
        raise SystemExit(f"unexpected table sizes {len(ints)} / {len(flts)}")
    fbits = [f32_bits(x) for x in flts]
    naive = sum(1 for x, b in zip(flts, fbits) if struct.unpack("<I", struct.pack("<f", float(x)))[0] != b)

    ib = b"".join(struct.pack("<I", v) for v in ints).hex()
    fb = b"".join(struct.pack("<I", v) for v in fbits).hex()
    wrap = lambda h: "\n".join(f'    "{h[i:i + 96]}"' for i in range(0, len(h), 96))  # noqa: E731
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "_iceborne_tables.py").write_text(
        '"""Generated by tools/savereader/gen_py_tables.py from Vendor/MHWCrypto/CryptoSecondLayer.cs. Do not edit."""\n'
        "# INTEGER_CONSTANTS: 4096 x u32 little-endian. FLOAT_CONSTANTS: 4096 x binary32 little-endian.\n"
        f"INTEGER_CONSTANTS_HEX = (\n{wrap(ib)}\n)\n"
        f"FLOAT_CONSTANTS_HEX = (\n{wrap(fb)}\n)\n",
        encoding="utf-8", newline="\n")

    data = OUT / "data"
    data.mkdir(exist_ok=True)
    for name in RESOURCES:
        shutil.copyfile(HERE / "Data" / name, data / name)
    print(f"ok: {len(ints)} ints, {len(flts)} floats ({naive} differ from naive double->float), "
          f"{len(RESOURCES)} resources copied")
    return 0


if __name__ == "__main__":
    sys.exit(main())
