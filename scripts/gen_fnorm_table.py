"""Generate the pure-Python text-search tables and parity fixtures from the REAL PostgreSQL database.

    python scripts/gen_fnorm_table.py table      # -> api/app/_fnorm_table.py
    python scripts/gen_fnorm_table.py fixtures   # -> tests/fixtures/{fnorm,trgm_pairs,search_golden}.json
    python scripts/gen_fnorm_table.py all

Talks to the `db` service via `docker compose exec -T db psql` (run from the repo root, Postgres must be up).
Strictly read-only: only SELECT statements are sent. Payloads travel as ASCII JSON inside a dollar-quoted literal.
"""
