def gen_golden() -> None:
    out = []
    for q_raw, typ, limit in GOLDEN_QUERIES:
        q = q_raw.strip()   # main.py strips before querying
        sql = bind(SEARCH_SQL, {"q": q, "type": typ, "limit": limit * 3})
        rows = query_json("SELECT coalesce(json_agg(t), '[]') FROM (" + sql + ") t", prefix="SET search_path = mhw, public;")
        api = sorted(rows, key=lambda r: (not r["prefix"], not r["contains"], -round(r["score"], 1),
                                          TYPE_PRIORITY.index(r["type"]) if r["type"] in TYPE_PRIORITY else 99))
        out.append({"q": q_raw, "type": typ, "limit": limit, "sql_limit": limit * 3,
                    "sql_rows": [[r["type"], r["id"], r["score"], r["prefix"], r["contains"],
                                  r["name_es"], r["name_en"]] for r in rows],
                    "api_ids": [[r["type"], r["id"]] for r in api[:limit]]})
    doc = {"meta": {"sql": SEARCH_SQL.strip(), "params": "q = q.strip(); type; limit = limit*3",
                    "sql_rows_columns": ["type", "id", "score(float4 as psycopg sees it)", "prefix", "contains",
                                         "name_es", "name_en"],
                    "api_ids": "sql_rows re-sorted exactly like main.py (stable) and cut to limit",
                    "ties": "ORDER BY has no unique tie-breaker: Postgres' order among rows with equal "
                            "(prefix, contains, score, length) is unspecified, and LIMIT may cut inside such a "
                            "group. Compare tie groups as sets."},
           "queries": out}
    (FIX / "search_golden.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"search_golden.json: {len(out)} queries")


