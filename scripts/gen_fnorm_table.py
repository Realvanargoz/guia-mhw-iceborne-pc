SEARCH_SQL = """
      WITH s AS (
        SELECT type, id, name_es, name_en, subtitle,
               f_norm(coalesce(name_es, '') || ' ' || coalesce(name_en, '')) AS doc,
               f_norm(%(q)s) AS nq
        FROM search_index
        WHERE (%(type)s::text IS NULL OR type = %(type)s)
      )
      SELECT type, id, name_es, name_en, subtitle,
             (doc LIKE '%%' || nq || '%%') AS contains,
             (f_norm(coalesce(name_es, '')) LIKE nq || '%%' OR f_norm(coalesce(name_en, '')) LIKE nq || '%%') AS prefix,
             word_similarity(nq, doc) AS score
      FROM s
      WHERE doc LIKE '%%' || nq || '%%' OR nq <%% doc
      ORDER BY prefix DESC, contains DESC, score DESC, length(coalesce(name_es, name_en))
      LIMIT %(limit)s"""
TYPE_PRIORITY = ["item", "monster", "armor_set", "layered", "achievement", "quest", "guide", "location",
                 "armor", "weapon", "skill", "decoration", "charm"]


def bind(sql: str, params: dict) -> str:
    import re

    def lit(v):
        if v is None:
            return "NULL"
        if isinstance(v, int):
            return str(v)
        # Unicode-escaped string constant (same type/semantics as a plain '...' literal) so the SQL stays ASCII
        body = "".join("''" if c == "'" else "\\\\" if c == "\\" else c if 32 <= ord(c) < 127
                       else "\\%04x" % ord(c) if ord(c) <= 0xFFFF else "\\+%06x" % ord(c) for c in v)
        return "U&'" + body + "'"

    return re.sub(r"%%|%\((\w+)\)s", lambda m: "%" if m.group(0) == "%%" else lit(params[m.group(1)]), sql)


