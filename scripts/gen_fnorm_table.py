def gen_fnorm_fixture(rng, rows, fnorm_keys) -> None:
    inputs = set()
    for r in rows:
        for k in ("es", "en", "sub"):
            if r[k]:
                inputs.add(r[k])
    inputs.update(TRICKY)
    inputs.update(rand_unicode(rng, fnorm_keys, 2500))
    inputs = sorted(inputs)
    res = query_json(f"""
      SELECT json_agg(json_build_array(x, public.f_norm(x)) ORDER BY o)
      FROM json_array_elements_text({payload(inputs)}) WITH ORDINALITY AS t(x, o)""")
    # LIKE cases: (value, pattern) -> value LIKE pattern
    vals = ["rathalos", "azure rathalos", "100% off", "a_b", "a\\b", "50%", "_athalos", "", "ñandu", "日本語",
            "rath%", "x", "abc", "a%b_c\\d", "\\", "%", "_", "ab", "ﬁsh", "ȿ"]
    needles = ["", "%", "_", "\\", "\\%", "\\_", "\\\\", "rath", "rath%", "_athalos", "a_b", "a\\_b", "%%", "__",
               "100\\%", "0%", "a\\", "\\a", "日", "_本", "%b%", "ñ", "a%b", "50", "\\x", "%\\", "ab\\"]
    like_cases = []
    for v in vals:
        for nd in needles:
            like_cases.append([v, "%" + nd + "%"])
            like_cases.append([v, nd + "%"])
            if not (nd.endswith("\\") and not nd.endswith("\\\\")):
                like_cases.append([v, nd])
    like_res = query_json(f"""
      SELECT json_agg(json_build_array(p->>0, p->>1, (p->>0) LIKE (p->>1)) ORDER BY o)
      FROM json_array_elements({payload(like_cases)}) WITH ORDINALITY AS t(p, o)""")
    out = {"meta": {"source": "SELECT x, public.f_norm(x) on the live PostgreSQL 17 (scripts/gen_fnorm_table.py)",
                    "count": len(res), "like_count": len(like_res)},
           "pairs": res, "like": like_res}
    (FIX / "fnorm.json").write_text(json.dumps(out, ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"fnorm.json: {len(res)} pairs, {len(like_res)} LIKE cases")


def mutate(rng: random.Random, s: str) -> str:
    op = rng.randrange(10)
    if not s:
        return s
    i = rng.randrange(len(s))
    if op == 0:
        return s[:rng.randint(1, len(s))]                      # prefix
    if op == 1:
        return s[:i] + s[i + 1:]                               # drop char
    if op == 2 and len(s) > 1:
        i = min(i, len(s) - 2)
        return s[:i] + s[i + 1] + s[i] + s[i + 2:]             # swap
    if op == 3:
        return s[:i] + rng.choice("abcdefghijklmnopqrstuvwxyzáéíóúñ") + s[i + 1:]  # replace
    if op == 4:
        return "".join(c for c in unicodedata.normalize("NFD", s) if not unicodedata.combining(c))
    if op == 5:
        words = s.split()
        return rng.choice(words) if words else s               # one word
    if op == 6:
        return s.upper()
    if op == 7:
        return s + " " + rng.choice(["x", "alfa", "ii", "beta", "+", "dragon", "s"])
    if op == 8:
        words = s.split()
        rng.shuffle(words)
        return " ".join(words)
    return s


def gen_trgm_fixture(rng, rows, queries) -> None:
    from app.textnorm import f_norm  # verified by fnorm.json
    docs = [r["doc"] for r in rows]
    names = [r[k] for r in rows for k in ("es", "en") if r[k]]
    pairs = []
    # 1) app-like: normalized query vs normalized doc (half from the same entity)
    for _ in range(2600):
        r = rng.choice(rows)
        name = r[rng.choice(["es", "en"])] or r["en"]
        q = mutate(rng, name)
        if rng.random() < 0.3:
            q = mutate(rng, q)
        doc = r["doc"] if rng.random() < 0.5 else rng.choice(docs)
        pairs.append([f_norm(q), doc])
    # 2) real query strings from the parity list vs random/related docs
    for q in queries:
        nq = f_norm(q.strip())
        for _ in range(3):
            pairs.append([nq, rng.choice(docs)])
        hits = [d for d in docs if nq and nq[:3] in d]
        for d in rng.sample(hits, min(3, len(hits))):
            pairs.append([nq, d])
    # 3) raw (un-normalized) strings: exercises pg_trgm's own lower-casing and word splitting
    for _ in range(700):
        a = mutate(rng, rng.choice(names))
        b = rng.choice(names) if rng.random() < 0.5 else a + " " + rng.choice(names)
        pairs.append([a, b])
    # 4) short strings (0-2 chars)
    shorts = ["", " ", "a", "z", "1", "-", "ab", "ra", "aj", "xx", "12", "ñ", "ü", "é", "ß", "İ", "日", "%", "_",
              "'", "a b", "Ab", "AB", "ǅ", "K", "ﬁ", "²", "٣", "ⅷ"]
    for _ in range(800):
        a = rng.choice(shorts) if rng.random() < 0.7 else "".join(
            rng.choice("abcdefghijklmnopqrstuvwxyzñü0123456789 -'") for _ in range(rng.randint(1, 2)))
        b = rng.choice(docs) if rng.random() < 0.6 else rng.choice(shorts + names[:50])
        pairs.append([a, b] if rng.random() < 0.85 else [b, a])
    # 5) unicode / multibyte-trigram heavy
    uni_words = ["日本語", "ドラゴン", "αβγ", "Ωμέγα", "привет", "Дракон", "çà", "ÉCOLE", "école", "İstanbul",
                 "istanbul", "Straße", "strasse", "ǅungla", "naïve", "Ñandú", "ﬁsh", "ＲＡＴＨ", "rath", "٣٤٥",
                 "ⅷⅸ", "Kelvin", "😀😀", "áb", "Ⱥȿ", "ŉŋ", "kjárr", "kjarr", "über", "uber", "ΣΑΣ", "σας"]
    for _ in range(900):
        a = " ".join(rng.choice(uni_words) for _ in range(rng.randint(1, 3)))
        if rng.random() < 0.5:
            b = mutate(rng, a) + " " + rng.choice(uni_words)
        else:
            b = " ".join(rng.choice(uni_words) for _ in range(rng.randint(1, 4)))
        pairs.append([a, b])
    # 6) edge cases
    edge = [["", ""], ["", "abc"], ["abc", ""], ["a", "a"], ["aa aa aa", "aa"], ["aa", "aa aa aa"],
            ["rathalos", "rathalos rathalos rathalos"], ["a" * 99, "a" * 50], ["a" * 50, "a" * 99],
            ["abcabcabc", "abc abc"], ["word", "w o r d"], ["w o r d", "word"], ["---", "---"], ["a-b-c", "abc"]]
    pairs.extend(edge)
    res = query_json(f"""
      SELECT json_agg(json_build_array(a, b, word_similarity(a, b)::text, word_similarity(a, b)::float8,
                                       similarity(a, b)::text, similarity(a, b)::float8, a <% b) ORDER BY o)
      FROM (SELECT p->>0 a, p->>1 b, o FROM json_array_elements({payload(pairs)}) WITH ORDINALITY AS t(p, o)) s""")
    out = {"meta": {"columns": ["a", "b", "word_similarity(a,b)::text", "word_similarity(a,b)::float8",
                                "similarity(a,b)::text", "similarity(a,b)::float8", "a <% b"],
                    "word_similarity_threshold": 0.6, "count": len(res)},
           "pairs": res}
    (FIX / "trgm_pairs.json").write_text(json.dumps(out, ensure_ascii=False, indent=0), encoding="utf-8")
    nz = sum(1 for p in res if p[3] > 0)
    print(f"trgm_pairs.json: {len(res)} pairs ({nz} with word_similarity > 0, {sum(p[6] for p in res)} <% true)")


