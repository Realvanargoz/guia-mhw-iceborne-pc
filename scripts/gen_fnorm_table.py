def rand_unicode(rng: random.Random, fnorm_keys: list[int], n: int) -> list[str]:
    pools = [
        lambda: chr(rng.randint(32, 126)),
        lambda: chr(rng.randint(0xA0, 0xFF)),
        lambda: chr(rng.randint(0x100, 0x24F)),
        lambda: chr(rng.randint(0x300, 0x36F)),
        lambda: chr(rng.randint(0x370, 0x3FF)),
        lambda: chr(rng.randint(0x400, 0x4FF)),
        lambda: chr(rng.randint(0x1E00, 0x1EFF)),
        lambda: chr(rng.randint(0x2000, 0x2BFF)),
        lambda: chr(rng.randint(0x4E00, 0x4FFF)),
        lambda: chr(rng.randint(0xFB00, 0xFB4F)),
        lambda: chr(rng.randint(0xFF01, 0xFF5E)),
        lambda: chr(rng.randint(0x1F300, 0x1F6FF)),
        lambda: chr(rng.choice(fnorm_keys)),
        lambda: chr(rng.choice(fnorm_keys)),
        lambda: chr(rng.choice([rng.randint(1, 0xD7FF), rng.randint(0xE000, 0x10FFFF)])),
    ]
    out = []
    for _ in range(n):
        s = "".join(rng.choice(pools)() for _ in range(rng.randint(1, 14)))
        out.append(s.replace("\x00", ""))
    return out


