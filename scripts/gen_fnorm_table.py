def ranges(cps: list[int]) -> list[tuple[int, int]]:
    out = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [tuple(r) for r in out]


def fmt_dict(name: str, d: dict[int, str]) -> str:
    items = [f"0x{k:x}:{ascii(v)}" for k, v in sorted(d.items())]
    lines, cur = [], ""
    for it in items:
        if len(cur) + len(it) + 1 > 110:
            lines.append(cur)
            cur = ""
        cur += it + ","
    lines.append(cur)
    return f"{name} = {{\n" + "\n".join(lines) + "\n}\n"


def gen_table() -> None:
    data = query_json(f"""
      SELECT json_build_object(
        'version', version(),
        'fnorm', (SELECT json_object_agg(cp, v) FROM
                    (SELECT cp, public.f_norm(chr(cp)) v FROM generate_series(1, 1114111) cp WHERE {SURR}) s
                  WHERE v <> chr(cp)),
        'lower', (SELECT json_object_agg(cp, v) FROM
                    (SELECT cp, lower(chr(cp)) v FROM generate_series(1, 1114111) cp WHERE {SURR}) s
                  WHERE v <> chr(cp)),
        'wordchr', (SELECT json_agg(cp ORDER BY cp) FROM generate_series(1, 1114111) cp
                    WHERE {SURR} AND cardinality(show_trgm(chr(cp))) > 0))""")
    fnorm = {int(k): v for k, v in data["fnorm"].items()}
    lower = {int(k): v for k, v in data["lower"].items()}
    word = data["wordchr"]
    # invariants the Python ports rely on
    assert {k: v for k, v in fnorm.items() if k < 128} == {c: chr(c + 32) for c in range(65, 91)}, "ASCII f_norm"
    assert {k: v for k, v in lower.items() if k < 128} == {c: chr(c + 32) for c in range(65, 91)}, "ASCII lower"
    assert all(len(v) == 1 for v in lower.values()), "lower() must be 1:1 per code point"
    assert [c for c in word if c < 128] == [c for c in range(128) if chr(c).isalnum()], "ASCII isalnum"
    wr = ranges(word)
    src = (f'"""GENERATED by scripts/gen_fnorm_table.py from the live database -- DO NOT EDIT.\n\n'
           f'{data["version"]}\n'
           f'FNORM: public.f_norm(chr(cp)) for every code point where it differs ({len(fnorm)} entries).\n'
           f'LOWER: lower(chr(cp)) where it differs ({len(lower)} entries, all 1:1; pg_trgm lower-casing).\n'
           f'WORDCHR_RANGES: inclusive code point ranges pg_trgm treats as word characters '
           f'({len(word)} code points).\n"""\n\n'
           + fmt_dict("FNORM", fnorm) + "\n" + fmt_dict("LOWER", lower) + "\n"
           + "WORDCHR_RANGES = (\n" + "\n".join(
               "".join(f"(0x{a:x},0x{b:x})," for a, b in wr[i:i + 8]) for i in range(0, len(wr), 8)) + "\n)\n")
    TABLE_PY.write_text(src, encoding="ascii", newline="\n")
    print(f"{TABLE_PY}: fnorm={len(fnorm)} lower={len(lower)} wordchr={len(word)} ranges={len(wr)}")


