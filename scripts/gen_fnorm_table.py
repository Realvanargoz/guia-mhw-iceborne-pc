SURR = "(cp < 55296 OR cp > 57343)"
DQ = "$pl$"


def psql(sql: str) -> str:
    sql = "SET client_encoding = 'UTF8';\n" + sql
    r = subprocess.run(["docker", "compose", "exec", "-T", "db", "psql", "-U", "mhw", "-d", "mhw", "-X", "-q",
                        "-At", "-v", "ON_ERROR_STOP=1", "-f", "-"],
                       input=sql.encode("ascii"), capture_output=True, cwd=ROOT)
    if r.returncode:
        sys.exit("psql failed: " + r.stderr.decode("utf-8", "replace"))
    return r.stdout.decode("utf-8")


def payload(obj) -> str:
    s = json.dumps(obj, ensure_ascii=True)
    assert DQ not in s
    return f"{DQ}{s}{DQ}::json"


def query_json(sql: str, prefix: str = ""):
    """Run a one-row/one-column json query. The value travels base64-encoded because psql's printer silently
    drops code points it deems invalid for display (e.g. the noncharacters U+1FFFE/U+1FFFF)."""
    import base64
    out = psql(prefix + f"\nSELECT encode(convert_to(({sql.strip().rstrip(';')})::text, 'UTF8'), 'base64');")
    return json.loads(base64.b64decode("".join(out.split())).decode("utf-8"))


