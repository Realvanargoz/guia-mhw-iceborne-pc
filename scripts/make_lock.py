"""Generate api/requirements.lock.txt (pinned + sha256 hashes) for the Windows build venv.

Usage (from the repo root, with the build venv python):
    .venv-build/Scripts/python.exe scripts/make_lock.py
Downloads the wheels for THIS interpreter/platform into a temp dir (pip download) and hashes them.
Install later with: pip install --require-hashes -r api/requirements.lock.txt
"""
from __future__ import annotations

import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "api" / "requirements.lock.txt"


def main() -> int:
    with tempfile.TemporaryDirectory() as td:
        subprocess.run([sys.executable, "-m", "pip", "download", "--only-binary=:all:", "-q", "-d", td,
                        "-r", str(ROOT / "api" / "requirements.txt"),
                        "-r", str(ROOT / "api" / "requirements-build.txt")], check=True)
        by_name: dict[str, list[tuple[str, str]]] = {}
        for f in sorted(Path(td).iterdir()):
            if f.suffix != ".whl":
                print("non-wheel artifact (sdist) found, abort:", f.name, file=sys.stderr)
                return 1
            name, ver = f.name.split("-")[:2]
            by_name.setdefault(name.lower().replace("_", "-"), []).append((ver, hashlib.sha256(f.read_bytes()).hexdigest()))
    lines = ["# Generated by scripts/make_lock.py (pip download + sha256). Platform: win_amd64 / CPython 3.14.",
             "# Install: pip install --require-hashes -r api/requirements.lock.txt"]
    for name in sorted(by_name):
        ver = by_name[name][0][0]
        lines.append(f"{name}=={ver} \\")
        hs = sorted({h for _, h in by_name[name]})
        lines.append(" \\n".join(f"    --hash=sha256:{h}" for h in hs))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(by_name)} packages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
